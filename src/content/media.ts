import type { Locale } from "@/i18n/config";

/**
 * Photography manifest.
 *
 * Every photo slot on the website is defined here. While a photo has no
 * `file`, the slot renders a designed brand panel instead (never a stock
 * placeholder or a fake photo). To add a photo:
 *
 *   1. Put the original (JPG/PNG, at least 2400px on the long side) in
 *      assets/photos/<id>.jpg
 *   2. Run `npm run photos` — this creates optimised WebP files in
 *      public/images/photos/ (several widths).
 *   3. Set `file: "<id>"` below and fill in `credit`.
 *
 * Rules (see docs/PHOTOGRAPHY.md):
 *   - Only licensed photos or original AI-generated images.
 *   - AI-generated people must never be presented as Dilek, staff or clients.
 *   - `dilek-portrait` must be a REAL photo of Dilek.
 *   - No before/after results, nothing sexualised.
 */
export type PhotoId =
  | "hero-portrait"
  | "hero-detail"
  | "zone-face"
  | "zone-body"
  | "zone-intimate"
  | "hygiene"
  | "aftercare"
  | "dilek-portrait"
  | "atmosphere";

export type Photo = {
  id: PhotoId;
  /** Base name of the optimised files in public/images/photos (set when available). */
  file?: string;
  /** Width/height ratio of the slot, e.g. 4/5 for portrait. */
  aspect: number;
  alt: Record<Locale, string>;
  /** Short art-direction brief (also used in docs/PHOTOGRAPHY.md). */
  brief: string;
  /** Must be a real photograph (no AI), e.g. of Dilek. */
  mustBeReal?: boolean;
  /** License / photographer / "AI-generated (tool)" for the record. */
  credit?: string;
  /** Focal point for object-position, e.g. "50% 30%". */
  focus?: string;
};

